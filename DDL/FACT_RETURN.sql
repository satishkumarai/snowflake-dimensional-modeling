create or replace TABLE ECOMMERCE.ANALYTICS.FACT_RETURN cluster by (RETURN_DATE_SK, PRODUCT_SK)(
	RETURN_SK NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder COMMENT 'Surrogate key',
	RETURN_DATE_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_DATE - date return was initiated',
	CUSTOMER_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_CUSTOMER',
	PRODUCT_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_PRODUCT',
	RETURN_REASON_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_RETURN_REASON',
	ORDER_NUMBER VARCHAR(16777216) COMMENT 'Degenerate dim - links to original order',
	RETURN_NUMBER VARCHAR(16777216) COMMENT 'Degenerate dim - return identifier',
	QUANTITY_RETURNED NUMBER(10,0) NOT NULL COMMENT 'Units returned (additive)',
	REFUND_AMOUNT NUMBER(12,2) NOT NULL COMMENT 'Refund issued (additive)',
	RESTOCKING_FEE NUMBER(10,2) NOT NULL DEFAULT 0 COMMENT 'Fee deducted from refund (additive)',
	ETL_LOADED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Row load timestamp',
	ETL_SOURCE VARCHAR(16777216) DEFAULT 'SEED' COMMENT 'Source system identifier',
	constraint PK_FACT_RETURN primary key (RETURN_SK),
	constraint FK_RETURN_DATE foreign key (RETURN_DATE_SK) references ECOMMERCE.ANALYTICS.DIM_DATE(DATE_SK),
	constraint FK_RETURN_CUSTOMER foreign key (CUSTOMER_SK) references ECOMMERCE.ANALYTICS.DIM_CUSTOMER(CUSTOMER_SK),
	constraint FK_RETURN_PRODUCT foreign key (PRODUCT_SK) references ECOMMERCE.ANALYTICS.DIM_PRODUCT(PRODUCT_SK),
	constraint FK_RETURN_REASON foreign key (RETURN_REASON_SK) references ECOMMERCE.ANALYTICS.DIM_RETURN_REASON(RETURN_REASON_SK)
)COMMENT='Returns fact table | Grain: one row per returned line item'
;