create or replace TABLE ECOMMERCE.ANALYTICS.FACT_ORDER_LINE cluster by (DATE_SK, PRODUCT_SK)(
	ORDER_LINE_SK NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder COMMENT 'Surrogate key',
	DATE_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_DATE',
	CUSTOMER_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_CUSTOMER',
	PRODUCT_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_PRODUCT',
	PAYMENT_METHOD_SK NUMBER(38,0) NOT NULL COMMENT 'FK to DIM_PAYMENT_METHOD',
	ORDER_NUMBER VARCHAR(16777216) COMMENT 'Degenerate dimension - order identifier',
	QUANTITY NUMBER(10,0) NOT NULL COMMENT 'Units ordered (additive)',
	UNIT_PRICE NUMBER(10,2) NOT NULL COMMENT 'Price per unit at time of sale (additive)',
	DISCOUNT_AMOUNT NUMBER(10,2) NOT NULL DEFAULT 0 COMMENT 'Discount applied (additive)',
	LINE_TOTAL NUMBER(12,2) NOT NULL COMMENT 'quantity * unit_price - discount (additive)',
	TAX_AMOUNT NUMBER(10,2) NOT NULL DEFAULT 0 COMMENT 'Tax on this line (additive)',
	ETL_LOADED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Row load timestamp',
	ETL_SOURCE VARCHAR(16777216) DEFAULT 'SEED' COMMENT 'Source system identifier',
	GEOGRAPHY_SK NUMBER(38,0) NOT NULL DEFAULT 0 COMMENT 'FK to DIM_GEOGRAPHY',
	SHIPPING_COST NUMBER(10,2) NOT NULL DEFAULT 0 COMMENT 'Shipping cost for this line (additive)',
	SHIP_DATE_SK NUMBER(38,0) COMMENT 'FK to DIM_DATE for ship date',
	DELIVERY_DATE_SK NUMBER(38,0) COMMENT 'FK to DIM_DATE for delivery date',
	constraint PK_FACT_ORDER_LINE primary key (ORDER_LINE_SK),
	constraint FK_FACT_DATE foreign key (DATE_SK) references ECOMMERCE.ANALYTICS.DIM_DATE(DATE_SK),
	constraint FK_FACT_CUSTOMER foreign key (CUSTOMER_SK) references ECOMMERCE.ANALYTICS.DIM_CUSTOMER(CUSTOMER_SK),
	constraint FK_FACT_PRODUCT foreign key (PRODUCT_SK) references ECOMMERCE.ANALYTICS.DIM_PRODUCT(PRODUCT_SK),
	constraint FK_FACT_PAYMENT foreign key (PAYMENT_METHOD_SK) references ECOMMERCE.ANALYTICS.DIM_PAYMENT_METHOD(PAYMENT_METHOD_SK),
	constraint FK_FACT_GEOGRAPHY foreign key (GEOGRAPHY_SK) references ECOMMERCE.ANALYTICS.DIM_GEOGRAPHY(GEOGRAPHY_SK)
)COMMENT='Order line fact table | Grain: one row per order line item'
;