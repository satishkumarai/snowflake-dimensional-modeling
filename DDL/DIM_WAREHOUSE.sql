create or replace TABLE ECOMMERCE.ANALYTICS.DIM_WAREHOUSE (
	WAREHOUSE_SK NUMBER(38,0) NOT NULL autoincrement start 0 increment 1 noorder COMMENT 'Surrogate key',
	WAREHOUSE_ID VARCHAR(16777216) NOT NULL COMMENT 'Natural key',
	WAREHOUSE_NAME VARCHAR(16777216) NOT NULL COMMENT 'Warehouse name',
	CITY VARCHAR(16777216) COMMENT 'Warehouse city',
	STATE VARCHAR(16777216) COMMENT 'State or province',
	COUNTRY VARCHAR(16777216) NOT NULL COMMENT 'Country',
	GEOGRAPHY_SK NUMBER(38,0) NOT NULL DEFAULT 0 COMMENT 'FK to DIM_GEOGRAPHY',
	CAPACITY_UNITS NUMBER(10,0) COMMENT 'Max storage units',
	ETL_LOADED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Row load timestamp',
	ETL_SOURCE VARCHAR(16777216) DEFAULT 'SEED' COMMENT 'Source system identifier',
	constraint PK_DIM_WAREHOUSE primary key (WAREHOUSE_SK)
)COMMENT='Warehouse/fulfillment center dimension'
