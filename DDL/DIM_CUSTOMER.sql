create or replace TABLE ECOMMERCE.ANALYTICS.DIM_CUSTOMER (
	CUSTOMER_SK NUMBER(38,0) NOT NULL autoincrement start 0 increment 1 noorder COMMENT 'Surrogate key',
	CUSTOMER_ID VARCHAR(16777216) NOT NULL COMMENT 'Natural key from source system',
	CUSTOMER_NAME VARCHAR(16777216) COMMENT 'Full name',
	EMAIL VARCHAR(16777216) COMMENT 'Email address',
	CITY VARCHAR(16777216) COMMENT 'City',
	STATE VARCHAR(16777216) COMMENT 'State or province',
	COUNTRY VARCHAR(16777216) COMMENT 'Country',
	REGION VARCHAR(16777216) COMMENT 'Sales region for regional reporting',
	CUSTOMER_SEGMENT VARCHAR(16777216) COMMENT 'Customer segment (Consumer, Corporate, etc.)',
	EFFECTIVE_FROM TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Row effective start',
	EFFECTIVE_TO TIMESTAMP_NTZ(9) DEFAULT CAST('9999-12-31' AS TIMESTAMP_NTZ(9)) COMMENT 'Row effective end',
	IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Current version flag',
	ETL_LOADED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP() COMMENT 'Row load timestamp',
	ETL_SOURCE VARCHAR(16777216) DEFAULT 'SEED' COMMENT 'Source system identifier',
	constraint PK_DIM_CUSTOMER primary key (CUSTOMER_SK)
)COMMENT='Customer dimension with SCD Type 2 for address history'
;