create or replace TABLE ECOMMERCE.ANALYTICS.DIM_DATE (
	DATE_SK NUMBER(38,0) NOT NULL COMMENT 'Surrogate key (YYYYMMDD format)',
	FULL_DATE DATE NOT NULL COMMENT 'Calendar date',
	DAY_OF_WEEK NUMBER(1,0) NOT NULL COMMENT 'Day of week (0=Mon, 6=Sun)',
	DAY_NAME VARCHAR(16777216) NOT NULL COMMENT 'Day name (Monday, Tuesday, etc.)',
	DAY_OF_MONTH NUMBER(2,0) NOT NULL COMMENT 'Day of month (1-31)',
	DAY_OF_YEAR NUMBER(3,0) NOT NULL COMMENT 'Day of year (1-366)',
	WEEK_OF_YEAR NUMBER(2,0) NOT NULL COMMENT 'ISO week number',
	MONTH_NUMBER NUMBER(2,0) NOT NULL COMMENT 'Month number (1-12)',
	MONTH_NAME VARCHAR(16777216) NOT NULL COMMENT 'Month name',
	QUARTER_NUMBER NUMBER(1,0) NOT NULL COMMENT 'Quarter (1-4)',
	QUARTER_NAME VARCHAR(16777216) NOT NULL COMMENT 'Quarter label (Q1-Q4)',
	YEAR_NUMBER NUMBER(4,0) NOT NULL COMMENT 'Calendar year',
	IS_WEEKEND BOOLEAN NOT NULL COMMENT 'True if Saturday or Sunday',
	IS_HOLIDAY BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'True if public holiday',
